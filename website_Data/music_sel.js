const player = document.getElementById('terminal-audio-engine');
const source = document.getElementById('audio-source');
const deckStatus = document.getElementById('deck-status-tag');
const visualizerElement = document.querySelector('.audio-hud-visualizer');
const heroSection = document.querySelector('.now-playing-hero');
const playerDashboard = document.querySelector('.persistent-audio-dashboard');

let parsedLyrics = [];

// Hide player and hero header by default on load if no track is selected
if (heroSection) heroSection.style.display = 'none';
if (playerDashboard) playerDashboard.style.display = 'none';

function parseLRC(rawText) {
    const lines = rawText.split('\n');
    const result = [];
    const timeReg = /\[(\d{2}):(\d{2})\]/;

    lines.forEach(line => {
        const match = timeReg.exec(line);
        if (match) {
            const minutes = parseInt(match[1], 10);
            const seconds = parseInt(match[2], 10);
            const timeInSeconds = minutes * 60 + seconds;
            const text = line.replace(timeReg, '').trim();
            result.push({ time: timeInSeconds, text: text });
        } else if (line.trim() !== '') {
            result.push({ time: -1, text: line.trim() });
        }
    });
    return result;
}

function renderLyricsContainer(lyricsArray) {
    const drawerLyrics = document.getElementById('drawer-lyrics-content');
    const mobileLyrics = document.getElementById('mobile-lyrics-content');

    const buildHTML = lyricsArray.map((item, index) => {
        if (item.text === "") return `<div class="lyric-line spacer" data-index="${index}"></div>`;
        return `<div class="lyric-line" data-time="${item.time}" data-index="${index}">${item.text}</div>`;
    }).join('');

    if (drawerLyrics) {
        drawerLyrics.innerHTML = buildHTML;
        drawerLyrics.classList.add('synced-lyrics-container');
    }
    if (mobileLyrics) {
        mobileLyrics.innerHTML = buildHTML;
        mobileLyrics.classList.add('synced-lyrics-container');
    }
}

function streamAudioEngine(trackKey, element) {
    const data = audioDatabase[trackKey];
    if (!data) {
        console.warn(`[AUDIO ERROR]: Track key "${trackKey}" not found in database.`);
        return;
    }

    // Unhide hero section and player dashboard when a song is chosen
    if (heroSection) heroSection.style.display = 'block';
    if (playerDashboard) playerDashboard.style.display = 'block';

    const heroTitle = document.getElementById('hero-track-title');
    const heroDesc = document.getElementById('hero-track-desc');
    const heroMeta = document.getElementById('hero-track-meta');
    if (heroTitle) heroTitle.innerText = data.title;
    if (heroDesc) heroDesc.innerText = data.desc;
    if (heroMeta) heroMeta.innerText = data.meta;

    const deckTitle = document.getElementById('deck-title');
    const deckThumb = document.getElementById('deck-thumb');
    if (deckTitle) deckTitle.innerText = data.title;
    if (deckThumb) deckThumb.src = data.thumb;

    const drawerTitle = document.getElementById('drawer-track-title');
    const mobileTitle = document.getElementById('mobile-lyrics-track-title');
    const mobileThumb = document.getElementById('mobile-lyrics-thumb');
    const drawerLyrics = document.getElementById('drawer-lyrics-content');
    const mobileLyrics = document.getElementById('mobile-lyrics-content');

    if (drawerTitle) drawerTitle.innerText = data.title;
    if (mobileTitle) mobileTitle.innerText = data.title;
    if (mobileThumb && data.thumb) mobileThumb.src = data.thumb;

    if (drawerLyrics) drawerLyrics.innerHTML = "[ DECRYPTING LYRICS DATASTREAM... ]";
    if (mobileLyrics) mobileLyrics.innerHTML = "[ DECRYPTING LYRICS DATASTREAM... ]";
    parsedLyrics = [];

    if (data.lyricsFile && data.lyricsFile.trim() !== '') {
        fetch(data.lyricsFile)
            .then(response => {
                if (!response.ok) throw new Error('Lyrics file not found');
                return response.text();
            })
            .then(text => {
                parsedLyrics = parseLRC(text);
                renderLyricsContainer(parsedLyrics);
            })
            .catch(error => {
                const errMsg = "[ ERROR: LYRICS FILE OFFLINE ]";
                if (drawerLyrics) drawerLyrics.innerText = errMsg;
                if (mobileLyrics) mobileLyrics.innerText = errMsg;
            });
    } else {
        const noLyricsMsg = "[ NO_LYRICS_NODE_ASSIGNED_FOR_THIS_TRACK ]";
        if (drawerLyrics) drawerLyrics.innerText = noLyricsMsg;
        if (mobileLyrics) mobileLyrics.innerText = noLyricsMsg;
    }

    source.src = data.file;
    source.type = data.format;
    player.load();
    player.play().catch(e => console.log("Playback prevented or loading...", e));

    document.querySelectorAll('.music-card').forEach(card => {
        card.classList.cardList ? card.classList.remove('active') : card.classList.remove('active');
    });
    if (element) {
        element.classList.add('active');
    }
}

// Stop Audio Function to clear selection and hide components
function stopAudioEngine() {
    if (player) {
        player.pause();
        player.currentTime = 0;
    }
    if (source) {
        source.src = "";
    }
    if (heroSection) heroSection.style.display = 'none';
    if (playerDashboard) playerDashboard.style.display = 'none';

    // Close desktop drawer if open
    const desktopDrawer = document.getElementById("lyrics-drawer-panel");
    if (desktopDrawer) desktopDrawer.classList.remove("open");

    // Clear active card states
    document.querySelectorAll('.music-card').forEach(card => {
        card.classList.remove('active');
    });
}

// Sync lyrics highlighting during audio playback
if (player) {
    player.addEventListener('timeupdate', () => {
        if (!parsedLyrics.length) return;
        const currentTime = player.currentTime;

        let activeIndex = -1;
        for (let i = 0; i < parsedLyrics.length; i++) {
            if (parsedLyrics[i].time !== -1 && currentTime >= parsedLyrics[i].time) {
                activeIndex = i;
            }
        }

        if (activeIndex !== -1) {
            ['drawer-lyrics-content', 'mobile-lyrics-content'].forEach(containerId => {
                const container = document.getElementById(containerId);
                if (!container) return;
                
                const lines = container.querySelectorAll('.lyric-line');
                lines.forEach((line, idx) => {
                    if (idx === activeIndex) {
                        if (!line.classList.contains('active')) {
                            line.classList.add('active');
                            line.scrollIntoView({ behavior: 'smooth', block: 'center' });
                        }
                    } else {
                        line.classList.remove('active');
                    }
                });
            });
        }
    });
}

// Bind Media Event State Readouts, Resizing, Font Zooming, and Stop Button Logic on page load
document.addEventListener("DOMContentLoaded", () => {
    if (player && deckStatus) {
        player.onplay = () => {
            deckStatus.innerText = 'STREAMING STREAM';
            deckStatus.style.color = '#00ffff';
            if (visualizerElement) visualizerElement.classList.add('playing');
        };
        player.onpause = () => {
            deckStatus.innerText = 'DECK PAUSED';
            deckStatus.style.color = '#ffae00';
            if (visualizerElement) visualizerElement.classList.remove('playing');
        };
        player.onended = () => {
            deckStatus.innerText = 'MANIFEST COMPLETE';
            deckStatus.style.color = '#888888';
            if (visualizerElement) visualizerElement.classList.remove('playing');
        };
    }

    // Bind Stop Button Trigger if present, or create it dynamically if missing
    let stopBtn = document.getElementById("stop-audio-btn");
    const hardwareCore = document.querySelector(".deck-media-hardware-core");
    if (!stopBtn && hardwareCore) {
        stopBtn = document.createElement("button");
        stopBtn.id = "stop-audio-btn";
        stopBtn.className = "tactical-lyrics-btn stop-btn";
        stopBtn.innerHTML = '<i class="fa-solid fa-stop"></i><span class="btn-text">STOP</span>';
        hardwareCore.prepend(stopBtn);
    }
    if (stopBtn) {
        stopBtn.addEventListener("click", stopAudioEngine);
    }

    const desktopDrawer = document.getElementById("lyrics-drawer-panel");
    const resizeHandle = document.getElementById("lyrics-resize-handle");
    const drawerCloseBtn = document.getElementById("lyrics-close-trigger");
    const fontGrowBtn = document.getElementById("font-grow-btn");
    const fontShrinkBtn = document.getElementById("font-shrink-btn");
    const drawerLyricsContent = document.getElementById("drawer-lyrics-content");

    let isResizing = false;
    let startX, startY, startWidth, startHeight;
    let currentFontSize = 13; // Default font size in pixels

    if (resizeHandle && desktopDrawer) {
        resizeHandle.addEventListener("mousedown", (e) => {
            isResizing = true;
            startX = e.clientX;
            startY = e.clientY;
            startWidth = desktopDrawer.offsetWidth;
            startHeight = desktopDrawer.offsetHeight;
            e.preventDefault();
        });

        window.addEventListener("mousemove", (e) => {
            if (!isResizing) return;
            const dx = startX - e.clientX;
            const dy = startY - e.clientY;
            
            const newWidth = startWidth + dx;
            const newHeight = startHeight + dy;

            if (newWidth >= 300 && newWidth <= 800) {
                desktopDrawer.style.width = newWidth + "px";
            }
            if (newHeight >= 200 && newHeight <= 700) {
                desktopDrawer.style.height = newHeight + "px";
                desktopDrawer.style.maxHeight = newHeight + "px";
            }
        });

        window.addEventListener("mouseup", () => {
            isResizing = false;
        });
    }

    // Helper to apply font size changes directly to lyric lines
    function updateLyricLinesFontSize(size) {
        if (!drawerLyricsContent) return;
        const lines = drawerLyricsContent.querySelectorAll('.lyric-line');
        lines.forEach(line => {
            line.style.fontSize = size + "px";
        });
    }

    // Font Scaling Controls (Min: 10px, Max: 22px)
    if (fontGrowBtn && drawerLyricsContent) {
        fontGrowBtn.addEventListener("click", () => {
            if (currentFontSize < 22) {
                currentFontSize += 2;
                updateLyricLinesFontSize(currentFontSize);
            }
        });
    }

    if (fontShrinkBtn && drawerLyricsContent) {
        fontShrinkBtn.addEventListener("click", () => {
            if (currentFontSize > 10) {
                currentFontSize -= 2;
                updateLyricLinesFontSize(currentFontSize);
            }
        });
    }

    // Reset panel dimensions and font size back to defaults when closed
    function resetDrawerState() {
        if (desktopDrawer) {
            desktopDrawer.style.width = "";
            desktopDrawer.style.height = "";
            desktopDrawer.style.maxHeight = "";
        }
        if (drawerLyricsContent) {
            currentFontSize = 13;
            updateLyricLinesFontSize(13);
        }
    }

    if (drawerCloseBtn) {
        drawerCloseBtn.addEventListener("click", () => {
            if (desktopDrawer) desktopDrawer.classList.remove("open");
            resetDrawerState();
        });
    }
});